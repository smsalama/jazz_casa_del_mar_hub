import chromium from '@sparticuz/chromium';
import { chromium as pw } from 'playwright-core';
import fs from 'fs';
const dir=process.argv[2]; const out=process.argv[3];
const b=await pw.launch({executablePath:await chromium.executablePath(),args:chromium.args,headless:true});
const p=await b.newPage({viewport:{width:375,height:800}});
const res=[];
const ok=(n,v,d)=>{res.push({check:n,pass:!!v,detail:d});};
await p.goto('file://'+dir+'/index.html'); await p.waitForTimeout(400);
let before=await p.getAttribute('.menu-button','aria-expanded');
await p.click('.menu-button'); let after=await p.getAttribute('.menu-button','aria-expanded');
ok('Public mobile menu opens (aria-expanded false to true, header data-open)',before==='false'&&after==='true'&&await p.evaluate(()=>document.querySelector('.site-header').hasAttribute('data-open')),before+'->'+after);
await p.screenshot({path:out+'/a1-menu-open-375.png'});
await p.keyboard.press('Escape'); ok('Escape closes menu',await p.getAttribute('.menu-button','aria-expanded')==='false');
await p.setViewportSize({width:1440,height:900});
const pb=p.locator('[data-pause-motion]:visible').first();
const a0=await pb.getAttribute('aria-pressed'); await pb.click(); const a1=await pb.getAttribute('aria-pressed');
const mo=await p.evaluate(()=>document.documentElement.getAttribute('data-motion'));
ok('Pause motion toggles aria-pressed and html data-motion',a0==='false'&&a1==='true'&&mo==='paused',a0+'->'+a1+' data-motion='+mo);
await pb.click(); ok('Pause motion toggles back',await pb.getAttribute('aria-pressed')==='false');
await p.goto('file://'+dir+'/admin-sign-in.html'); await p.waitForTimeout(300);
const t=p.locator('[data-toggle-password]').first(); const id=await t.getAttribute('aria-controls');
const ty0=await p.evaluate(i=>document.getElementById(i).type,id); await t.click();
const ty1=await p.evaluate(i=>document.getElementById(i).type,id); const ap=await t.getAttribute('aria-pressed');
ok('Password Show toggle works',ty0==='password'&&ty1==='text'&&ap==='true',ty0+'->'+ty1+' pressed='+ap);
await p.setViewportSize({width:375,height:800}); await p.goto('file://'+dir+'/admin-editor.html'); await p.waitForTimeout(300);
await p.click('.admin-menu-button'); ok('Admin menu opens',await p.getAttribute('.admin-menu-button','aria-expanded')==='true');
fs.writeFileSync(out+'/a1-results.json',JSON.stringify(res,null,1)); console.log(JSON.stringify(res,null,1));
await b.close();
